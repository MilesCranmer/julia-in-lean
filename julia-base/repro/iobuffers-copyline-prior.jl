# copyline(out, s; keep=false) strips bytes that were in out before the call
function run(prefix, line)
    s = Base.BufferStream()
    write(s, line)
    closewrite(s)
    out = IOBuffer()
    write(out, prefix)
    copyline(out, s)
    String(take!(out))
end
a = run("a\n", "")
b = run("ab\r", "\nrest")
println("\"a\\n\" + exhausted stream: ", repr(a), "; \"ab\\r\" + \"\\n\": ", repr(b))
v = UInt8[0x0d, 0x0d]; popfirst!(v)
out = IOBuffer(v; read=true, write=true, truncate=true)
s = Base.BufferStream(); write(s, "\n"); closewrite(s)
copyline(out, s)
println("buffer over a vector with memory offset: position = ", position(out), ", bytesavailable = ", bytesavailable(out))
